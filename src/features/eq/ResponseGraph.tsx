import { useMemo, useRef } from "react";
import { bandGrids, responseGrid } from "../../dsp/response";
import type { PEQProfile } from "../../dsp/types";
import { useEQStore } from "../../state/eq-store";

const W = 640;
const H = 240;
const PAD = { left: 44, right: 12, top: 12, bottom: 24 };
const F_MIN = 20;
const F_MAX = 20000;
const SAMPLE_RATE = 48000;

function xToFreq(x: number): number {
	const lo = Math.log10(F_MIN);
	const hi = Math.log10(F_MAX);
	return 10 ** (lo + ((x - PAD.left) / (W - PAD.left - PAD.right)) * (hi - lo));
}

function freqToX(frequency: number): number {
	const lo = Math.log10(F_MIN);
	const hi = Math.log10(F_MAX);
	const t =
		(Math.log10(Math.min(F_MAX, Math.max(F_MIN, frequency))) - lo) / (hi - lo);
	return PAD.left + t * (W - PAD.left - PAD.right);
}

function dbToY(db: number, maxDb: number): number {
	const t = (db + maxDb) / (2 * maxDb);
	return PAD.top + (1 - t) * (H - PAD.top - PAD.bottom);
}

function yToDb(y: number, maxDb: number): number {
	const t = 1 - (y - PAD.top) / (H - PAD.top - PAD.bottom);
	return t * 2 * maxDb - maxDb;
}

function pathFor(
	points: { frequency: number; db: number }[],
	maxDb: number,
): string {
	return points
		.map(
			(p, i) =>
				`${i === 0 ? "M" : "L"}${freqToX(p.frequency).toFixed(1)},${dbToY(p.db, maxDb).toFixed(1)}`,
		)
		.join(" ");
}

/**
 * EQ response graph generated by the SAME response engine the tests assert
 * (response.ts) — never approximated with separate UI math. Log frequency
 * axis, 0 dB reference, per-band curves, draggable band dots.
 */
export function ResponseGraph({ profile }: { profile: PEQProfile }) {
	const svgRef = useRef<SVGSVGElement>(null);
	const total = useMemo(
		() => responseGrid(profile, SAMPLE_RATE, 160),
		[profile],
	);
	const bands = useMemo(() => bandGrids(profile, SAMPLE_RATE, 96), [profile]);
	const peak = useMemo(
		() => Math.max(6, ...total.map((p) => Math.abs(p.db)), 0.001),
		[total],
	);
	const maxDb = Math.ceil(Math.min(24, peak));

	const updateFromPointer = (
		bandId: string,
		clientX: number,
		clientY: number,
	) => {
		const svg = svgRef.current;
		if (!svg) return;
		const rect = svg.getBoundingClientRect();
		const x = ((clientX - rect.left) / rect.width) * W;
		const y = ((clientY - rect.top) / rect.height) * H;
		const frequency = Math.min(20000, Math.max(20, Math.round(xToFreq(x))));
		const gain = Math.round(yToDb(y, maxDb) * 2) / 2;
		useEQStore.getState().updateBand(bandId, { frequency, gain });
	};

	return (
		<figure aria-label="Equalizer frequency response">
			<svg
				ref={svgRef}
				viewBox={`0 0 ${W} ${H}`}
				role="img"
				aria-label={`Total response, plus or minus ${maxDb} decibels, 20 hertz to 20 kilohertz`}
				className="w-full rounded-xl border border-line bg-abyss"
			>
				{[20, 50, 100, 200, 500, 1000, 2000, 5000, 10000, 20000].map((f) => (
					<g key={f}>
						<line
							x1={freqToX(f)}
							y1={PAD.top}
							x2={freqToX(f)}
							y2={H - PAD.bottom}
							stroke="currentColor"
							strokeOpacity={0.12}
						/>
						<text
							x={freqToX(f)}
							y={H - 8}
							textAnchor="middle"
							fontSize="10"
							fill="currentColor"
							opacity={0.6}
						>
							{f >= 1000 ? `${f / 1000}k` : f}
						</text>
					</g>
				))}
				{[-maxDb, -maxDb / 2, 0, maxDb / 2, maxDb].map((db) => (
					<g key={db}>
						<line
							x1={PAD.left}
							y1={dbToY(db, maxDb)}
							x2={W - PAD.right}
							y2={dbToY(db, maxDb)}
							stroke="currentColor"
							strokeOpacity={db === 0 ? 0.5 : 0.12}
							strokeDasharray={db === 0 ? undefined : "3 3"}
						/>
						<text
							x={PAD.left - 5}
							y={dbToY(db, maxDb) + 3}
							textAnchor="end"
							fontSize="10"
							fill="currentColor"
							opacity={0.6}
						>
							{db > 0 ? `+${db}` : db}
						</text>
					</g>
				))}
				{bands.map((band) => (
					<path
						key={band.id}
						d={pathFor(band.points, maxDb)}
						fill="none"
						stroke="currentColor"
						strokeOpacity={0.3}
						strokeWidth={1.5}
					/>
				))}
				<path
					d={pathFor(total, maxDb)}
					fill="none"
					stroke="var(--color-accent)"
					strokeWidth={2.5}
				/>
				{profile.bands
					.filter((b) => b.enabled)
					.map((band) => {
						const totalAt = total.reduce((best, p) =>
							Math.abs(Math.log10(p.frequency / band.frequency)) <
							Math.abs(Math.log10(best.frequency / band.frequency))
								? p
								: best,
						);
						return (
							<g key={band.id}>
								<circle
									cx={freqToX(band.frequency)}
									cy={dbToY(totalAt?.db ?? 0, maxDb)}
									r={9}
									tabIndex={0}
									role="slider"
									aria-label={`${band.type} band at ${band.frequency} hertz, gain ${band.gain} decibels`}
									aria-valuemin={20}
									aria-valuemax={20000}
									aria-valuenow={Math.round(band.frequency)}
									aria-valuetext={`${band.frequency} Hz, ${band.gain} dB`}
									fill="var(--color-accent)"
									stroke="var(--color-abyss)"
									strokeWidth={2}
									style={{ cursor: "grab" }}
									onPointerDown={(e) => {
										(e.target as SVGCircleElement).setPointerCapture(
											e.pointerId,
										);
										const move = (ev: PointerEvent) =>
											updateFromPointer(band.id, ev.clientX, ev.clientY);
										const up = (ev: PointerEvent) => {
											updateFromPointer(band.id, ev.clientX, ev.clientY);
											window.removeEventListener("pointermove", move);
											window.removeEventListener("pointerup", up);
										};
										window.addEventListener("pointermove", move);
										window.addEventListener("pointerup", up);
									}}
									onKeyDown={(e) => {
										const step = e.shiftKey ? 10 : 1;
										if (e.key === "ArrowLeft") {
											e.preventDefault();
											useEQStore.getState().updateBand(band.id, {
												frequency: Math.max(
													20,
													Math.round(band.frequency / 2 ** (step / 12)),
												),
											});
										} else if (e.key === "ArrowRight") {
											e.preventDefault();
											useEQStore.getState().updateBand(band.id, {
												frequency: Math.min(
													20000,
													Math.round(band.frequency * 2 ** (step / 12)),
												),
											});
										} else if (e.key === "ArrowUp") {
											e.preventDefault();
											useEQStore
												.getState()
												.updateBand(band.id, { gain: band.gain + 0.5 * step });
										} else if (e.key === "ArrowDown") {
											e.preventDefault();
											useEQStore
												.getState()
												.updateBand(band.id, { gain: band.gain - 0.5 * step });
										}
									}}
								/>
							</g>
						);
					})}
			</svg>
			<figcaption className="mt-1 text-center text-[11px] text-muted">
				Drag points to tune frequency and gain · arrow keys work when focused
			</figcaption>
		</figure>
	);
}
